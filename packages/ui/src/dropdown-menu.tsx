import * as React from 'react';
import { DropdownMenu as DropdownMenuPrimitive } from 'radix-ui';
import { cn } from './cn.js';

const popoverClass =
  'z-50 min-w-32 overflow-x-hidden overflow-y-auto rounded-lg border bg-popover p-1 text-popover-foreground shadow-card origin-(--radix-dropdown-menu-content-transform-origin) data-[side=bottom]:[--popover-y:-4px] data-[side=left]:[--popover-x:4px] data-[side=right]:[--popover-x:-4px] data-[side=top]:[--popover-y:4px] data-[state=closed]:animate-popover-out data-[state=open]:animate-popover-in motion-reduce:animate-none';

